"""Validate papers.yaml against taxonomy.yaml and regenerate the README paper index.

Usage:
    python scripts/build_index.py          # validate and rewrite README index block
    python scripts/build_index.py --check  # validate and fail if README index is stale
"""
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- PAPER-INDEX:BEGIN (generated by scripts/build_index.py, do not edit) -->"
END = "<!-- PAPER-INDEX:END -->"
REQUIRED = ["id", "short", "title", "first_public", "url", "routes", "tags", "status", "added"]
STATUS_LABEL = {"inbox": "待筛", "triaged": "待写", "card": "速读", "deep-read": "精读"}


def load():
    papers = yaml.safe_load((ROOT / "papers.yaml").read_text())["papers"]
    taxonomy = yaml.safe_load((ROOT / "taxonomy.yaml").read_text())
    return papers, taxonomy


def validate(papers, taxonomy):
    errors = []
    routes, tags, status = set(taxonomy["routes"]), set(taxonomy["tags"]), set(taxonomy["status"])
    problems = set(taxonomy["problems"])
    for pid, n in Counter(p.get("id") for p in papers).items():
        if n > 1:
            errors.append(f"duplicate id: {pid}")
    for p in papers:
        pid = p.get("id", "<missing id>")
        for key in REQUIRED:
            if p.get(key) in (None, "", []):
                errors.append(f"{pid}: missing {key}")
        if not isinstance(p.get("problems"), list):
            errors.append(f"{pid}: problems must be a list (use [] for baseline or background work)")
        errors += [f"{pid}: unknown problem {x}" for x in p.get("problems") or [] if x not in problems]
        if not re.fullmatch(r"\d{4}(-\d{2})?", str(p.get("first_public", ""))):
            errors.append(f"{pid}: first_public must be YYYY or YYYY-MM")
        if p.get("arxiv") and not re.fullmatch(r"\d{4}\.\d{4,5}", str(p["arxiv"])):
            errors.append(f"{pid}: bad arxiv id {p['arxiv']}")
        errors += [f"{pid}: unknown route {r}" for r in p.get("routes", []) if r not in routes]
        errors += [f"{pid}: unknown tag {t}" for t in p.get("tags", []) if t not in tags]
        if p.get("status") not in status:
            errors.append(f"{pid}: unknown status {p.get('status')}")
        for key in ("card", "deep"):
            if p.get(key) and not (ROOT / p[key]).is_file():
                errors.append(f"{pid}: {key} file not found: {p[key]}")
        if p.get("status") in ("card", "deep-read") and not p.get("card"):
            errors.append(f"{pid}: status {p['status']} requires card")
        if p.get("status") == "deep-read" and not p.get("deep"):
            errors.append(f"{pid}: status deep-read requires deep")
    return errors


def links(p):
    out = []
    if p.get("arxiv"):
        out.append(f"[arXiv](https://arxiv.org/abs/{p['arxiv']})")
    else:
        out.append(f"[论文]({p['url']})")
    if p.get("code"):
        out.append(f"[代码]({p['code']})")
    if p.get("card"):
        out.append(f"[速读]({p['card']})")
    if p.get("deep"):
        out.append(f"[精读]({p['deep']})")
    return " · ".join(out)


def render(papers, taxonomy):
    lines = [BEGIN, ""]
    counts = Counter(p["status"] for p in papers)
    summary = "，".join(f"{STATUS_LABEL[s]} {counts[s]}" for s in taxonomy["status"] if counts[s])
    lines += [f"共收录 {len(papers)} 篇（{summary}）。同一篇论文可出现在多条路线下；“问题”列对应上文 P1-P10。", ""]
    nos = {k: v["code"] for k, v in taxonomy["problems"].items()}
    for key, route in taxonomy["routes"].items():
        rows = sorted((p for p in papers if key in p["routes"]), key=lambda p: (str(p["first_public"]), p["short"]))
        lines += [f"### {route['name']}（`{key}`）", "", f"{route['scope']}", ""]
        if not rows:
            lines += ["_暂无收录，待补检。_", ""]
            continue
        lines += ["| 时间 | 工作 | 问题 | 标签 | 状态 | 链接 |", "| --- | --- | --- | --- | --- | --- |"]
        for p in rows:
            title = p["title"].replace("|", "\\|")
            tags = " ".join(f"`{t}`" for t in p["tags"])
            probs = " ".join(sorted((nos[x] for x in p["problems"]), key=lambda s: int(s[1:]))) or "—"
            lines.append(
                f"| {p['first_public']} | **{p['short']}**<br>{title} | {probs} | {tags} | {STATUS_LABEL[p['status']]} | {links(p)} |"
            )
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def main():
    papers, taxonomy = load()
    errors = validate(papers, taxonomy)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text()
    if BEGIN not in readme or END not in readme:
        print("README.md is missing the PAPER-INDEX markers", file=sys.stderr)
        return 1
    head, rest = readme.split(BEGIN, 1)
    tail = rest.split(END, 1)[1]
    updated = head + render(papers, taxonomy) + tail
    if "--check" in sys.argv:
        if updated != readme:
            print("README paper index is stale; run: python scripts/build_index.py", file=sys.stderr)
            return 1
        print(f"ok: {len(papers)} papers, README index up to date")
        return 0
    readme_path.write_text(updated)
    print(f"ok: {len(papers)} papers, README index regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
