"""Validate the AlphaRadar registry and regenerate everything derived from it.

Sources:   papers.yaml, taxonomy.yaml, and the hand-written notes and topics.
Generated: README.md blocks PROBLEMS and STATUS, INDEX.md, and the header of every reading card
           (from the start of the file to the META:END marker).
Checks:    taxonomy values, dates and paths in papers.yaml; README problem headings and
           topics/problems.md against the problem labels; required fields of reading cards and
           required sections of deep reads.

Usage:
    python scripts/build_index.py          # validate and rewrite generated content
    python scripts/build_index.py --check  # validate and fail if generated content is stale
"""
import os
import re
import sys
from collections import Counter
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
GEN = "generated by scripts/build_index.py; do not edit"
META_BEGIN = f"<!-- META:BEGIN ({GEN}) -->"
META_END = "<!-- META:END -->"
STATUS_LABEL = {"inbox": "待筛", "triaged": "待写", "card": "速读", "deep-read": "精读"}
REQUIRED = ["id", "short", "title", "summary", "first_public", "url", "routes", "tags", "status", "added", "checked"]
CARD_FIELDS = ["主要工作/创新点", "针对问题与证据", "局限", "可参考点"]
DEEP_SECTIONS = ["核心结论", "针对的问题", "实验", "未披露"]
DATE = re.compile(r"\d{4}-\d{2}-\d{2}")
RECENT = 5
THIN = 2  # problems with at most this many works are reported as coverage gaps


def load():
    papers = yaml.safe_load((ROOT / "papers.yaml").read_text())["papers"]
    taxonomy = yaml.safe_load((ROOT / "taxonomy.yaml").read_text())
    return papers, taxonomy


# ---------- helpers ----------

def pcode(taxonomy, key):
    return taxonomy["problems"][key]["code"]


def sorted_problems(p, taxonomy):
    return sorted(p["problems"], key=lambda k: int(pcode(taxonomy, k)[1:]))


def has_note(p):
    return p["status"] in ("card", "deep-read")


def mentioned(text, shorts):
    """Return the paper short names mentioned in text, matching longer names first."""
    found = set()
    for s in sorted(shorts, key=len, reverse=True):
        pat = re.compile(r"(?<![A-Za-z0-9-])" + re.escape(s) + r"(?![A-Za-z0-9-])")
        if pat.search(text):
            found.add(s)
            text = pat.sub(" ", text)
    return found


def card_field(body, name):
    m = re.search(rf"^\* \*\*{re.escape(name)}：\*\*(.*?)(?=^\* \*\*|\Z)", body, re.M | re.S)
    return m.group(1).strip() if m else None


def cell(value):
    return str(value).replace("|", "\\|").replace("\n", " ")


def paper_link(p, label=None):
    if p.get("arxiv"):
        return f"[{label or 'arXiv:' + str(p['arxiv'])}](https://arxiv.org/abs/{p['arxiv']})"
    return f"[{label or '论文页'}]({p['url']})"


def heading(p):
    title = p["title"]
    return title if title.lower().startswith(p["short"].lower()) else f"{p['short']}：{title}"


# ---------- validation ----------

def validate(papers, taxonomy):
    errors = []
    routes, tags, status, problems = (set(taxonomy[k]) for k in ("routes", "tags", "status", "problems"))
    for field in ("id", "short"):
        for value, n in Counter(p.get(field) for p in papers).items():
            if n > 1:
                errors.append(f"duplicate {field}: {value}")
    for p in papers:
        pid = p.get("id", "<missing id>")
        for key in REQUIRED:
            if p.get(key) in (None, "", []):
                errors.append(f"{pid}: missing {key}")
        if not isinstance(p.get("problems"), list):
            errors.append(f"{pid}: problems must be a list (use [] for baseline or background work)")
        errors += [f"{pid}: unknown problem {x}" for x in p.get("problems") or [] if x not in problems]
        errors += [f"{pid}: unknown route {r}" for r in p.get("routes") or [] if r not in routes]
        errors += [f"{pid}: unknown tag {t}" for t in p.get("tags") or [] if t not in tags]
        if p.get("status") not in status:
            errors.append(f"{pid}: unknown status {p.get('status')}")
        fp = str(p.get("first_public", ""))
        if not re.fullmatch(r"\d{4}(-\d{2})?", fp):
            errors.append(f"{pid}: first_public must be YYYY or YYYY-MM")
        if p.get("arxiv"):
            a = str(p["arxiv"])
            if not re.fullmatch(r"\d{4}\.\d{4,5}", a):
                errors.append(f"{pid}: bad arxiv id {a}")
            elif fp > f"20{a[:2]}-{a[2:4]}":
                errors.append(f"{pid}: first_public {fp} is later than the month in arXiv id {a}")
        for key in ("added", "checked"):
            if p.get(key) and not DATE.fullmatch(str(p[key])):
                errors.append(f"{pid}: {key} must be YYYY-MM-DD")
        for key in ("card", "deep"):
            if p.get(key) and not (ROOT / p[key]).is_file():
                errors.append(f"{pid}: {key} file not found: {p[key]}")
        if has_note(p) and not p.get("card"):
            errors.append(f"{pid}: status {p['status']} requires card")
        if p.get("status") == "deep-read" and not p.get("deep"):
            errors.append(f"{pid}: status deep-read requires deep")
    return errors


def check_readme_problems(readme, taxonomy):
    heads = dict(re.findall(r"^### (P\d+) (.+)$", readme, re.M))
    return [
        f"README.md: heading for {v['code']} must read '### {v['code']} {v['name']}'"
        for v in taxonomy["problems"].values()
        if heads.get(v["code"]) != v["name"]
    ]


def check_problem_doc(papers, taxonomy):
    rel = "topics/problems.md"
    parts = re.split(r"^## (P\d+) (.+)$", (ROOT / rel).read_text(), flags=re.M)
    secs = {parts[i]: (parts[i + 1].strip(), parts[i + 2]) for i in range(1, len(parts), 3)}
    shorts = [p["short"] for p in papers]
    errors = [f"{rel}: unknown section {c}" for c in secs if c not in {v["code"] for v in taxonomy["problems"].values()}]
    for key, prob in taxonomy["problems"].items():
        code = prob["code"]
        if code not in secs:
            errors.append(f"{rel}: missing section ## {code} {prob['name']}")
            continue
        name, body = secs[code]
        if name != prob["name"]:
            errors.append(f"{rel}: heading for {code} must read '## {code} {prob['name']}'")
        named = mentioned(body, shorts)
        labelled = {p["short"] for p in papers if key in p["problems"]}
        required = {p["short"] for p in papers if key in p["problems"] and has_note(p)}
        errors += [f"{rel}: {s} is labelled {code} in papers.yaml but not listed under {code}" for s in sorted(required - named)]
        errors += [f"{rel}: {s} is listed under {code} but not labelled {code} in papers.yaml" for s in sorted(named - labelled)]
    return errors


def check_card(p, text, taxonomy):
    errors, debt = [], Counter()
    rel = p["card"]
    if META_END not in text:
        return [f"{rel}: missing {META_END} marker"], debt
    body = text.split(META_END, 1)[1]
    values = {}
    for name in CARD_FIELDS:
        values[name] = card_field(body, name)
        if values[name] is None:
            errors.append(f"{rel}: missing field * **{name}：**")
    if values["局限"] is not None and values["局限"].startswith("待补"):
        debt["局限"] += 1
    ev = values["针对问题与证据"]
    if ev is not None:
        found = {f"P{n}" for n in re.findall(r"(?<![A-Za-z0-9])P(\d+)(?!\d)", ev)}
        want = {pcode(taxonomy, k) for k in p["problems"]}
        if found != want:
            errors.append(f"{rel}: 针对问题与证据 mentions {sorted(found) or 'none'}, papers.yaml labels {sorted(want) or 'none'}")
        if p["problems"] and re.search(r"证据：\s*待补", ev):
            debt["证据"] += 1
    return errors, debt


def check_deep(p):
    heads = re.findall(r"^#{2,3} (.+)$", (ROOT / p["deep"]).read_text(), re.M)
    return [f"{p['deep']}: needs a section heading containing '{k}'" for k in DEEP_SECTIONS if not any(k in h for h in heads)]


# ---------- rendering ----------

def render_card_header(p, taxonomy):
    probs = "；".join(f"{pcode(taxonomy, k)} {taxonomy['problems'][k]['name']}" for k in sorted_problems(p, taxonomy))
    if p.get("code"):
        label = re.sub(r"^https?://(www\.)?github\.com/", "", p["code"]).rstrip("/")
        code = f"[{label}]({p['code']})" + (f"；{p['code_note']}" if p.get("code_note") else "")
    else:
        code = p.get("code_note") or "未见官方开源"
    rows = [
        ("一句话", p["summary"]),
        ("首次公开", p["first_public"]),
        ("版本", p.get("versions") or "—"),
        ("会议 / 期刊", p.get("venue") or "—"),
        ("论文", paper_link(p)),
        ("代码", code),
        ("作者单位", p.get("affiliation") or "—"),
        ("路线", " ".join(f"`{r}`" for r in p["routes"])),
        ("标签", " ".join(f"`{t}`" for t in p["tags"])),
        ("针对问题", probs or "无（基线或背景工作）"),
    ]
    if p.get("deep"):
        target = os.path.relpath(ROOT / p["deep"], (ROOT / p["card"]).parent).replace(os.sep, "/")
        rows.append(("精读", f"[{p['short']} 精读]({target})"))
    rows.append(("状态核查", p["checked"]))
    lines = [f"# {heading(p)}", "", META_BEGIN, "", "| 项目 | 内容 |", "| --- | --- |"]
    lines += [f"| {k} | {cell(v)} |" for k, v in rows]
    return "\n".join(lines + ["", META_END])


def links(p):
    out = [paper_link(p, "arXiv" if p.get("arxiv") else "论文")]
    if p.get("code"):
        out.append(f"[代码]({p['code']})")
    if has_note(p):
        out.append(f"[速读]({p['card']})")
    if p.get("deep"):
        out.append(f"[精读]({p['deep']})")
    if not has_note(p):
        out.append(STATUS_LABEL[p["status"]])
    return " · ".join(out)


def summary_line(papers, taxonomy):
    counts = Counter(p["status"] for p in papers)
    detail = "，".join(f"{STATUS_LABEL[s]} {counts[s]}" for s in taxonomy["status"] if counts[s])
    return f"共收录 {len(papers)} 篇（{detail}）"


def render_index(papers, taxonomy):
    probs = list(taxonomy["problems"].items())
    rows = sorted(papers, key=lambda p: (str(p["first_public"]), p["short"]), reverse=True)
    lines = [
        "# 论文索引",
        "",
        "> 本文件由 `scripts/build_index.py` 根据 `papers.yaml` 生成，请勿手改。问题编号的含义见 README“出发点：因子挖掘面临的问题”，路线定义见 `taxonomy.yaml`。",
        "",
        summary_line(papers, taxonomy) + "。",
        "",
        "## 1. 总表",
        "",
        "按首次公开时间倒序。",
        "",
        "| 时间 | 工作 | 一句话 | 问题 | 路线 | 链接 |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for p in rows:
        work = f"**{p['short']}**" + (f"（{p['venue']}）" if p.get("venue") else "")
        codes = " ".join(pcode(taxonomy, k) for k in sorted_problems(p, taxonomy)) or "—"
        routes = " ".join(f"`{r}`" for r in p["routes"])
        lines.append(f"| {p['first_public']} | {cell(work)} | {cell(p['summary'])} | {codes} | {routes} | {links(p)} |")
    lines += ["", "## 2. 问题 × 工作矩阵", "", "“●”表示该工作针对这个问题；末行是各问题的工作数。", ""]
    lines.append("| 工作 | " + " | ".join(v["code"] for _, v in probs) + " |")
    lines.append("| --- |" + " :---: |" * len(probs))
    for p in rows:
        marks = " | ".join("●" if k in p["problems"] else " " for k, _ in probs)
        lines.append(f"| {cell(p['short'])} | {marks} |")
    totals = " | ".join(str(sum(k in p["problems"] for p in papers)) for k, _ in probs)
    lines += [f"| **合计** | {totals} |", "", "## 3. 按路线", "", "同一篇工作可以属于多条路线。", ""]
    for key, route in taxonomy["routes"].items():
        members = sorted((p for p in papers if key in p["routes"]), key=lambda p: (str(p["first_public"]), p["short"]))
        lines += [f"### {route['name']}（`{key}`，{len(members)} 篇）", "", route["scope"], ""]
        if members:
            items = [
                (f"[{p['short']}]({p['card']})" if has_note(p) else p["short"]) + f"（{p['first_public']}）"
                for p in members
            ]
            lines += [" · ".join(items), ""]
        else:
            lines += ["_暂无收录，待补检。_", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_problem_table(papers, taxonomy):
    lines = ["| 编号 | 问题 | 核心矛盾 | 所在环节 | 收录 |", "| --- | --- | --- | --- | ---: |"]
    for key, v in taxonomy["problems"].items():
        n = sum(key in p["problems"] for p in papers)
        lines.append(f"| {v['code']} | {cell(v['name'])} | {cell(v['tension'])} | {cell(v['stage'])} | {n} |")
    return "\n".join(lines)


def render_status(papers, taxonomy, debt):
    lines = [f"{summary_line(papers, taxonomy)}，完整列表见[论文索引](INDEX.md)。", "", "| 路线 | 篇数 |", "| --- | ---: |"]
    for key, route in taxonomy["routes"].items():
        lines.append(f"| {route['name']}（`{key}`） | {sum(key in p['routes'] for p in papers)} |")
    empty_routes = [f"`{k}`" for k in taxonomy["routes"] if not any(k in p["routes"] for p in papers)]
    thin = [v["code"] for k, v in taxonomy["problems"].items() if sum(k in p["problems"] for p in papers) <= THIN]
    gaps = []
    if empty_routes:
        gaps.append(f"- 暂无收录的路线：{'、'.join(empty_routes)}。")
    if thin:
        gaps.append(f"- 收录不超过 {THIN} 篇的问题：{'、'.join(thin)}。")
    if debt:
        gaps.append(f"- 速读卡待补：局限 {debt['局限']} 篇，证据 {debt['证据']} 篇。")
    if gaps:
        lines += ["", "覆盖缺口：", ""] + gaps
    recent = sorted(papers, key=lambda p: (str(p["added"]), str(p["first_public"])), reverse=True)[:RECENT]
    lines += ["", "最近收录：", ""]
    for p in recent:
        name = f"[{p['short']}]({p['card']})" if has_note(p) else p["short"]
        lines.append(f"- {p['added']} {name}：{p['summary']}")
    return "\n".join(lines)


def replace_block(text, name, content, errors):
    m = re.search(rf"<!-- {name}:BEGIN[^>]*-->.*?<!-- {name}:END -->", text, re.S)
    if not m:
        errors.append(f"README.md: missing <!-- {name}:BEGIN --> / <!-- {name}:END --> markers")
        return text
    return text[: m.start()] + f"<!-- {name}:BEGIN ({GEN}) -->\n\n{content}\n\n<!-- {name}:END -->" + text[m.end():]


# ---------- main ----------

def main():
    papers, taxonomy = load()
    errors = validate(papers, taxonomy)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    readme_path = ROOT / "README.md"
    readme = readme_path.read_text()
    errors += check_readme_problems(readme, taxonomy)
    errors += check_problem_doc(papers, taxonomy)
    debt, outputs = Counter(), {}
    for p in papers:
        if p.get("card"):
            path = ROOT / p["card"]
            text = path.read_text()
            e, d = check_card(p, text, taxonomy)
            errors += e
            debt += d
            if META_END in text:
                outputs[path] = render_card_header(p, taxonomy) + text.split(META_END, 1)[1]
        if p.get("deep"):
            errors += check_deep(p)
    readme = replace_block(readme, "PROBLEMS", render_problem_table(papers, taxonomy), errors)
    readme = replace_block(readme, "STATUS", render_status(papers, taxonomy, debt), errors)
    outputs[readme_path] = readme
    outputs[ROOT / "INDEX.md"] = render_index(papers, taxonomy)
    if errors:
        print("\n".join(errors), file=sys.stderr)
        return 1
    stale = {path: text for path, text in outputs.items() if not path.exists() or path.read_text() != text}
    if "--check" in sys.argv:
        if stale:
            names = "\n".join(f"  {path.relative_to(ROOT)}" for path in stale)
            print(f"generated content is stale; run: python scripts/build_index.py\n{names}", file=sys.stderr)
            return 1
        print(f"ok: {len(papers)} papers, generated content up to date")
        return 0
    for path, text in stale.items():
        path.write_text(text)
    print(f"ok: {len(papers)} papers, {len(stale)} file(s) regenerated")
    return 0


if __name__ == "__main__":
    sys.exit(main())
